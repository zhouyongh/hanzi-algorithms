/**
 * 人工标注的 IDS 结构集（构形准确率评测用）。
 *
 * 取这些字公认的 IDS 结构（左右 / 上下 / 左上包围 / 全包围 / 独体）。
 * 单独放在这里，是为了让评测台、瓶颈定位、将来的监督学习共用同一份标注——
 * 标注只有一份，评测结果才可比。
 *
 * ## 结构符口径
 *
 * 按 **CHISE/IDS 惯例**：
 * - ⿰ 左形右声、⿱ 上形右声…（上形下声）、⿵ 左上包围、⿴ 全体包围、⿻ 独体。
 *
 * ## 选字口径
 *
 * 1. **字必须在篆书层里查得到**——算法只跑篆书字形，查不到就没有可评的对象。
 *    早期版本有 24 个标注字在篆书层里没有（草、花、問的简体重文形式等），
 *    被评测脚本**静默跳过**，于是分母是 46 而不是 70——而跳掉的多是 ⿱/⿵/⿴，
 *    样本被系统性偏向左右与独体，准确率因此虚高。现在脚本会明确报出
 *    跳过了几个、为什么。
 * 2. **说文部首要落在 IDS 的第一个部件上**（左 / 上 / 包围位）。
 *    算法是「以说文部为形符」推构形的，部首在右边的字（郵、郊、郎，邑部）
 *    或部首在下边的字（布，巾部）语义不同，混进来会污染指标，故不收。
 * 3. 同一个字不重复收；繁体、异体字用篆书层里的那个写法。
 *
 * ## 关键分组：说文部首是不是整字
 *
 * 說文 540 部里有 **60 来个部本身就是合体字**（林、里、男、宮、明、朙…）。
 * 对这些字，「部首 + 剩余部分」这个前提**不成立**——部首就是整字，
 * 剩下的部分必然是空的，算法只能给出 ⿻。把这类字混进准确率的分母里
 * 会把数字抬高近 40 个百分点（实测 155 字里有 61 个属于这一类）。
 *
 * 所以分成三组，各组分开报：
 * - `LABELED`：**说文部首 ≠ 整字**，是算法真正能分解的字 —— 头号指标。
 * - `SELF_RADICAL`：说文部首就是整字，且 IDS 也是独体 —— 平凡正确，单列。
 * - `SELF_RADICAL_COMPOUND`：说文部首就是整字，但 IDS 说是合体
 *   （林 = ⿰木木、里 = ⿱田土、男 = ⿱田力、宮 = ⿱宀呂）——
 *   算法的前提不成立，单独报出来，不计入任何准确率。
 */

